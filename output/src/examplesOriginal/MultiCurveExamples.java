package examplesOriginal;
import boundary.*;
public class MultiCurveExamples {
	public static void main(String[] args){
		//Prepare a list of simple curves
		int[] z = {0,2,1,3};
		SurfaceWord sw = new SurfaceWord(z);
		//MultiCurve lengths
		int n = 6;
		//Prepare a curvelist
		CurveList cl;
		cl = new CurveList(sw);
		PrimitiveDoublyCyclicWord pdcw = new PrimitiveDoublyCyclicWord(new int[1], sw.length());
		SimpleCurve sc = new SimpleCurve(pdcw, sw);
		while(sc.length()<n+1){
			cl.add(sc);
			sc = sc.next();
		}
		
		/****************************************/
		/*            MultiCurves               */
		/****************************************/
		//MultiCurve are generated by MultiCurveInterator
		//MultiCurveIterator iterates though every
		//multicurve with length n by using a CurveList
		//MultiCurve also requires one to feed the set of possible
		//sizes combination of the individual curves.
		MultiCurveIterator m = new MultiCurveIterator(cl, n, sw, Helpers.partition(n));
		int count = 0;
		while(m.hasNext()){
			MultiCurve c = m.next();
			count++;
			System.out.println(c);
		}
		System.out.println(count);
		
		
		/****************************************/
		/*      MultiCurve With 2 Components    */
		/****************************************/
		m = new MultiCurveIterator(cl, n, sw, Helpers.partition(n,2));
		count = 0;
		while(m.hasNext()){
			MultiCurve c = m.next();
			count++;
			System.out.println(c);
		}
		System.out.println(count);
		
		/***************************************************************/
		/*  MultiCurve With 2 Components with at most 1 intersection   */
		/***************************************************************/
		System.out.println("MultiCurve With 2 Components with at most 1 intersection");
		m = new MultiCurveIterator(cl, n, sw, Helpers.partition(n,2));
		count = 0;
		while(m.hasNext()){
			MultiCurve c = m.next();
			if(c.intersections()<2){
				count++;
				System.out.println(c);
			}
		}
		System.out.println(count);
		
		
		/***************************************************************/
		/*  Number of MultiCurve With 2 components with k intersection */
		/***************************************************************/		
		System.out.println("Number of MultiCurve With 2 components with k intersection");
		m.reset();
		int[] stats = IntersectionStatistic.intersectionCount(m);
		for(int i=0;i<stats.length;i++){
			System.out.println(i+" "+stats[i]);
		}
	}
}
