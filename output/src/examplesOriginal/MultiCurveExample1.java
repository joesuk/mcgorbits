package examplesOriginal;
import boundary.CurveList;
import boundary.Helpers;
import boundary.MultiCurve;
import boundary.MultiCurveIterator;
import boundary.PrimitiveDoublyCyclicWord;
import boundary.SimpleCurve;
import boundary.SurfaceWord;


public class MultiCurveExample1 {
	public static void main(String[] args){
		//Prepare a list of simple curves
		int[] z = {0,2,1,3};
		SurfaceWord sw = new SurfaceWord(z);
		//MultiCurve lengths
		int n = 6;
		//Prepare a curvelist
		CurveList cl;
		cl = new CurveList(sw);
		PrimitiveDoublyCyclicWord pdcw = new PrimitiveDoublyCyclicWord(new int[1], sw.length());
		SimpleCurve sc = new SimpleCurve(pdcw, sw);
		while(sc.length()<n+1){
			cl.add(sc);
			sc = sc.next();
		}
		
		//END PREPARATION
		
		/****************************************/
		/*            MultiCurves               */
		/****************************************/
		//MultiCurve are generated by MultiCurveInterator
		//MultiCurveIterator iterates though every
		//multicurve with length n by using a CurveList
		//MultiCurve also requires one to feed the set of possible
		//sizes combination of the individual curves.
		MultiCurveIterator m = new MultiCurveIterator(cl, n, sw, Helpers.partition(n));
		int count = 0;
		while(m.hasNext()){
			MultiCurve c = m.next();
			count++;
			System.out.println(c);
		}
		System.out.println(count);
	}
}
